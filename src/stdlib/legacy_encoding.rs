//! Unicode-to-byte mappings for PHP's single-byte HTML entity encodings.
//!
//! The tables are the public Encoding Standard indexes, expressed in byte
//! order. Windows undefined slots stay explicit because PHP leaves numeric
//! references to those unrepresentable byte positions unchanged.

const UNDEFINED: u16 = 0xffff;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum LegacyEncoding {
    Iso88591,
    Iso885915,
    Iso88595,
    Ibm866,
    Koi8R,
    MacRoman,
    Windows1251,
    Windows1252,
}

impl LegacyEncoding {
    pub(super) fn parse(name: &str) -> Option<Self> {
        Some(match name.to_ascii_lowercase().as_str() {
            "iso-8859-1" | "iso8859-1" => Self::Iso88591,
            "iso-8859-15" | "iso8859-15" => Self::Iso885915,
            "iso-8859-5" | "iso8859-5" => Self::Iso88595,
            "cp866" | "ibm866" | "866" => Self::Ibm866,
            "koi8-r" | "koi8-ru" | "koi8r" => Self::Koi8R,
            "macroman" => Self::MacRoman,
            "cp1251" | "windows-1251" | "win-1251" => Self::Windows1251,
            "cp1252" | "windows-1252" | "1252" => Self::Windows1252,
            _ => return None,
        })
    }

    pub(super) fn encode(self, codepoint: u32) -> Option<u8> {
        if codepoint < 0x80 {
            return Some(codepoint as u8);
        }
        match self {
            Self::Iso88591 => u8::try_from(codepoint).ok(),
            Self::Iso885915 => encode_iso_8859_15(codepoint),
            Self::Iso88595 => encode_from_index(codepoint, &ISO_8859_5),
            Self::Ibm866 => encode_from_index(codepoint, &IBM866),
            Self::Koi8R => encode_from_index(codepoint, &KOI8_R),
            Self::MacRoman => encode_from_index(codepoint, &MACINTOSH),
            Self::Windows1251 => encode_from_index(codepoint, &WINDOWS_1251),
            Self::Windows1252 => encode_from_index(codepoint, &WINDOWS_1252),
        }
    }
}

fn encode_from_index(codepoint: u32, index: &[u16; 128]) -> Option<u8> {
    let codepoint = u16::try_from(codepoint).ok()?;
    index
        .iter()
        .position(|candidate| *candidate != UNDEFINED && *candidate == codepoint)
        .map(|position| position as u8 + 0x80)
}

fn encode_iso_8859_15(codepoint: u32) -> Option<u8> {
    let replacement = match codepoint {
        0x20ac => Some(0xa4),
        0x0160 => Some(0xa6),
        0x0161 => Some(0xa8),
        0x017d => Some(0xb4),
        0x017e => Some(0xb8),
        0x0152 => Some(0xbc),
        0x0153 => Some(0xbd),
        0x0178 => Some(0xbe),
        _ => None,
    };
    replacement.or_else(|| {
        let byte = u8::try_from(codepoint).ok()?;
        (!matches!(byte, 0xa4 | 0xa6 | 0xa8 | 0xb4 | 0xb8 | 0xbc | 0xbd | 0xbe)).then_some(byte)
    })
}

