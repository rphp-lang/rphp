#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_index_slot_has_the_expected_byte_contract() {
        for (encoding, index) in [
            (LegacyEncoding::Iso88595, &ISO_8859_5),
            (LegacyEncoding::Ibm866, &IBM866),
            (LegacyEncoding::Koi8R, &KOI8_R),
            (LegacyEncoding::MacRoman, &MACINTOSH),
            (LegacyEncoding::Windows1251, &WINDOWS_1251),
            (LegacyEncoding::Windows1252, &WINDOWS_1252),
        ] {
            for byte in 0_u8..0x80 {
                assert_eq!(encoding.encode(u32::from(byte)), Some(byte));
            }
            for (position, codepoint) in index.iter().copied().enumerate() {
                if codepoint == UNDEFINED {
                    assert_eq!(encoding.encode(position as u32 + 0x80), None);
                } else {
                    assert_eq!(
                        encoding.encode(u32::from(codepoint)),
                        Some(position as u8 + 0x80)
                    );
                }
            }
        }
    }

    #[test]
    fn latin9_replacements_displace_the_original_latin1_codepoints() {
        assert_eq!(LegacyEncoding::Iso885915.encode(0x20ac), Some(0xa4));
        assert_eq!(LegacyEncoding::Iso885915.encode(0x00a4), None);
        assert_eq!(LegacyEncoding::Iso885915.encode(0x0178), Some(0xbe));
        assert_eq!(LegacyEncoding::Iso885915.encode(0x00be), None);
    }

    #[test]
    fn latin_indexes_cover_every_defined_byte_slot() {
        for byte in 0x80_u8..=0xff {
            assert_eq!(LegacyEncoding::Iso88591.encode(u32::from(byte)), Some(byte));

            let latin9_codepoint = match byte {
                0xa4 => 0x20ac,
                0xa6 => 0x0160,
                0xa8 => 0x0161,
                0xb4 => 0x017d,
                0xb8 => 0x017e,
                0xbc => 0x0152,
                0xbd => 0x0153,
                0xbe => 0x0178,
                _ => u32::from(byte),
            };
            assert_eq!(
                LegacyEncoding::Iso885915.encode(latin9_codepoint),
                Some(byte)
            );
        }
    }

    #[test]
    fn documented_aliases_are_ascii_case_insensitive() {
        assert_eq!(
            LegacyEncoding::parse("IBM866"),
            Some(LegacyEncoding::Ibm866)
        );
        assert_eq!(
            LegacyEncoding::parse("win-1251"),
            Some(LegacyEncoding::Windows1251)
        );
        assert_eq!(
            LegacyEncoding::parse("1252"),
            Some(LegacyEncoding::Windows1252)
        );
        assert_eq!(
            LegacyEncoding::parse("macroman"),
            Some(LegacyEncoding::MacRoman)
        );
        assert_eq!(LegacyEncoding::parse("UTF-8"), None);
    }
}
